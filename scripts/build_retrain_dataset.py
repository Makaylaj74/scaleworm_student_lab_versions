"""Build leakage-safe YOLO datasets for the detector retrain on the Monday manual series.

Source annotations: ``validation/monday_manual_series/{images,labels}`` — 722 MJ
box-corrected Scene-1 frames (worm_count == number of boxes). This is ~8x the
original v2/v3 training data.

Held-out TEST (never trained on): the pre-existing acceptance gates, scored later with
their OWN independent counts (clicks / hand counts, a different counting method than the
box-drawing used for the training labels):
  - clear-window recall gate  : validation/clear_window_handcount/handcount_sheet.csv (39)
  - blurry Feb+May-2024 gate   : notebooks/model_comparison_handcount.csv               (31)

Leakage rule (lab standard = DAY level, stricter than frame-id): any Monday frame whose
calendar day matches a gate frame's day is removed from training. The Monday series has
up to ~8 slots per day, so one gate frame on a Monday would otherwise leak ~8 same-day
near-duplicates into training.

Outputs two datasets (symlinked images+labels, so no copy bloat):
  datasets/scaleworm_retrain_clear/  - clear era only  (pre 2023-08-11 camera swap)
  datasets/scaleworm_retrain_all/    - all eras (clear + blurry post-Aug-2023)
each with images/{train,val}, labels/{train,val}, data.yaml. Internal train/val split is
also DAY-level (seeded) and only used for early stopping; the real test is the external gate.

Run: python scripts/build_retrain_dataset.py
"""

from __future__ import annotations

import argparse
import csv
import glob
import random
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
MONDAY = REPO / "validation" / "monday_manual_series"
CLEAR_GATE = REPO / "validation" / "clear_window_handcount" / "handcount_sheet.csv"
BLURRY_GATE = REPO / "notebooks" / "model_comparison_handcount.csv"

# The -2023 camera swap (soft-focus onset) ~2023-08-11; before = clear era, after = blurry.
SWAP_DAY = "20230811"
SEED = 20260930
VAL_DAY_FRACTION = 0.15


def day_of(stem: str) -> str:
    """CAMHDA301-YYYYMMDDThhmmss... -> 'YYYYMMDD'."""
    return stem.split("-")[1][:8]


def era_of(stem: str) -> str:
    return "clear" if day_of(stem) < SWAP_DAY else "blurry"


def counted_stems(csv_path: Path) -> set[str]:
    """Frame ids that carry a real (non-empty) human count."""
    out: set[str] = set()
    if not csv_path.exists():
        return out
    with csv_path.open() as f:
        for row in csv.DictReader(f):
            fid = row.get("frame_id") or row.get("stem") or ""
            cnt = (row.get("worm_count") or row.get("human_count") or "").strip()
            if fid and cnt not in ("", "nan"):
                out.add(fid)
    return out


def validate_label(path: Path) -> int:
    """Return box count; raise if any line is not a valid class-0 YOLO row in [0,1]."""
    n = 0
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) != 5:
            raise ValueError(f"{path.name}: expected 5 fields, got {len(parts)}")
        cls, *coords = parts
        if cls != "0":
            raise ValueError(f"{path.name}: non-zero class {cls}")
        for c in coords:
            v = float(c)
            if not 0.0 <= v <= 1.0:
                raise ValueError(f"{path.name}: coord {v} out of [0,1]")
        n += 1
    return n


def image_for(stem: str) -> Path:
    for ext in (".png", ".jpg", ".jpeg"):
        p = MONDAY / "images" / f"{stem}{ext}"
        if p.exists():
            return p
    raise FileNotFoundError(f"no image for {stem}")


def build_dataset(name: str, train_stems: list[str], val_stems: list[str]) -> Path:
    root = REPO / "datasets" / name
    for sub in ("images/train", "images/val", "labels/train", "labels/val"):
        d = root / sub
        # clean stale symlinks from a prior build
        if d.exists():
            for p in d.iterdir():
                p.unlink()
        d.mkdir(parents=True, exist_ok=True)
    for split, stems in (("train", train_stems), ("val", val_stems)):
        for stem in stems:
            img = image_for(stem)
            (root / "images" / split / img.name).symlink_to(img)
            (root / "labels" / split / f"{stem}.txt").symlink_to(
                MONDAY / "labels" / f"{stem}.txt"
            )
    (root / "data.yaml").write_text(
        f"# Auto-generated by build_retrain_dataset.py (seed {SEED}).\n"
        f"# {name}: {len(train_stems)} train / {len(val_stems)} val (day-level split).\n"
        f"# Held-out TEST = external gates, scored via gate scripts (NOT here).\n"
        f"path: {root}\n"
        f"train: images/train\n"
        f"val: images/val\n"
        f"names:\n  0: scale_worm\n"
    )
    return root


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true", help="report only, build nothing")
    args = ap.parse_args()

    monday = sorted(Path(p).stem for p in glob.glob(str(MONDAY / "labels" / "*.txt")))
    # validate every label up front (fail fast on a corrupt annotation)
    boxes = {s: validate_label(MONDAY / "labels" / f"{s}.txt") for s in monday}

    clear_gate = counted_stems(CLEAR_GATE)
    blurry_gate = counted_stems(BLURRY_GATE)
    gate = clear_gate | blurry_gate
    gate_days = {day_of(s) for s in gate}

    safe = [s for s in monday if day_of(s) not in gate_days]
    removed = [s for s in monday if day_of(s) in gate_days]

    # DAY-level internal val split over the safe pool, stratified by era.
    rng = random.Random(SEED)
    days_by_era: dict[str, list[str]] = {"clear": [], "blurry": []}
    for d in sorted({day_of(s) for s in safe}):
        era = "clear" if d < SWAP_DAY else "blurry"
        days_by_era[era].append(d)
    val_days: set[str] = set()
    for era, days in days_by_era.items():
        days = days[:]
        rng.shuffle(days)
        k = max(1, round(len(days) * VAL_DAY_FRACTION))
        val_days.update(days[:k])

    def split_of(stem: str) -> str:
        return "val" if day_of(stem) in val_days else "train"

    all_train = [s for s in safe if split_of(s) == "train"]
    all_val = [s for s in safe if split_of(s) == "val"]
    clear_train = [s for s in all_train if era_of(s) == "clear"]
    clear_val = [s for s in all_val if era_of(s) == "clear"]

    # --- report ---
    print(f"Monday annotated frames : {len(monday)}  ({sum(boxes.values())} boxes)")
    print(
        f"gate frames (test)      : clear={len(clear_gate)} blurry={len(blurry_gate)} "
        f"union={len(gate)} over {len(gate_days)} days"
    )
    print(f"removed by day-level    : {len(removed)}")
    print(
        f"leakage-safe pool       : {len(safe)}  "
        f"({dict(Counter(era_of(s) for s in safe))})"
    )
    print(
        f"internal val days       : {len(val_days)} / "
        f"{len({day_of(s) for s in safe})} days"
    )
    print(f"ALL dataset  : train={len(all_train)} val={len(all_val)}")
    print(f"CLEAR dataset: train={len(clear_train)} val={len(clear_val)}")

    # --- leakage assertions (the whole point) ---
    train_days = {day_of(s) for s in all_train}
    val_days = {day_of(s) for s in all_val}
    assert not (train_days & val_days), "train/val share a day"
    assert not (train_days & gate_days), "train leaks a gate day"
    assert not (val_days & gate_days), "val leaks a gate day"
    assert not (set(all_train) & gate), "train leaks a gate frame"
    print("leakage checks PASSED (train/val/test day-disjoint)")

    if args.dry_run:
        print("dry-run: no datasets written")
        return

    r1 = build_dataset("scaleworm_retrain_all", all_train, all_val)
    r2 = build_dataset("scaleworm_retrain_clear", clear_train, clear_val)
    print(f"wrote {r1}")
    print(f"wrote {r2}")

    # persist the held-out test manifest for the gate step
    test_manifest = REPO / "datasets" / "retrain_test_manifest.csv"
    with test_manifest.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["frame_id", "era", "in_clear_gate", "in_blurry_gate"])
        for s in sorted(gate):
            w.writerow([s, era_of(s), int(s in clear_gate), int(s in blurry_gate)])
    print(f"wrote {test_manifest} ({len(gate)} held-out test frames)")


if __name__ == "__main__":
    main()
